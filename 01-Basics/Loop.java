public class Loop {
    public static void main(String[] args) {

        // WHILE LOOP

        int i = 1;
        while(i<=4){
            System.out.println("Hi"+i);
            i++;
        }   

        // DO WHILE LOOP

        do {
            System.out.println("Hello World!");
        }while(false);


        // FOR LOOP

        for(int j = 1; j<=4;j++){
            System.out.println("Hi"+(j-1));
        }

    }
}
